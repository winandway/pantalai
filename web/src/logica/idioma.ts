export const TEXTOS: Record<Idioma, Record<Clave, string>> = { en, es };
export type ClaveTexto = Clave;

export type Traductor = (clave: Clave) => string;
export const ContextoIdioma = createContext<{ idioma: Idioma; t: Traductor; cambiar: (i: Idioma) => void }>({
  idioma: 'en',
  t: (c) => en[c],
  cambiar: () => undefined,
});
export const useIdioma = () => useContext(ContextoIdioma);

export function idiomaGuardado(): Idioma {
  try {
    const v = localStorage.getItem('pantalai:idioma');
    if (v === 'en' || v === 'es') return v;
  } catch {
    /* sin almacenamiento */
  }
  return 'en';
}

export function textoError(t: Traductor, codigo: string): string {
  const clave = `error.${codigo}` as Clave;
  return clave in en ? t(clave) : t('error.servidor');
}

export function haceCuanto(ms: number, idioma: Idioma, ahora = Date.now()): string {
  const rtf = new Intl.RelativeTimeFormat(idioma, { numeric: 'auto' });
  const s = Math.round((ms - ahora) / 1000);
  const abs = Math.abs(s);
  if (abs < 60) return rtf.format(s, 'second');
  if (abs < 3600) return rtf.format(Math.round(s / 60), 'minute');
  if (abs < 86400) return rtf.format(Math.round(s / 3600), 'hour');
  if (abs < 86400 * 30) return rtf.format(Math.round(s / 86400), 'day');
  if (abs < 86400 * 365) return rtf.format(Math.round(s / (86400 * 30)), 'month');
  return rtf.format(Math.round(s / (86400 * 365)), 'year');
}
